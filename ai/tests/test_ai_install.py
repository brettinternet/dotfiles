from __future__ import annotations

import os
from pathlib import Path
import subprocess
import tempfile
import unittest


ROOT = Path(__file__).resolve().parents[2]


class AiInstallTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.home = Path(self.temporary.name)
        self.environment = {
            **os.environ,
            "DOTFILES": str(ROOT),
            "HOME": str(self.home),
        }

    def run_command(
        self, *arguments: str, expected_code: int = 0
    ) -> subprocess.CompletedProcess[str]:
        completed = subprocess.run(
            arguments,
            text=True,
            capture_output=True,
            cwd=ROOT,
            env=self.environment,
            check=False,
        )
        self.assertEqual(
            expected_code, completed.returncode, completed.stderr or completed.stdout
        )
        return completed

    def repository_status(self) -> str:
        completed = subprocess.run(
            ["git", "status", "--porcelain"],
            text=True,
            capture_output=True,
            cwd=ROOT,
            check=False,
        )
        self.assertEqual(0, completed.returncode, completed.stderr)
        return completed.stdout

    def test_command_adapters_are_generated_without_duplicate_claude_commands(
        self,
    ) -> None:
        before = self.repository_status()
        legacy_command = self.home / ".claude/commands/pr-review-draft.md"
        unmanaged_command = self.home / ".claude/commands/manual.md"
        legacy_command.parent.mkdir(parents=True)
        legacy_command.write_text(
            "---\ndescription: legacy\n---\n\n"
            "<!-- Generated by install-agent-commands. -->\n"
        )
        unmanaged_command.write_text("Unmanaged command\n")
        unmanaged_opencode_command = (
            self.home / ".config/opencode/commands/manual.md"
        )
        unmanaged_opencode_command.parent.mkdir(parents=True)
        unmanaged_opencode_command.write_text("Unmanaged OpenCode command\n")

        self.run_command("ai/.bin/install-agent-commands")

        generated_skill = self.home / ".agents/skills/pr-review-draft/SKILL.md"
        claude_skill = self.home / ".claude/skills/pr-review-draft/SKILL.md"
        self.assertIn("Generated by install-agent-commands.", generated_skill.read_text())
        self.assertIn("argument-hint: <pr-number|url>", generated_skill.read_text())
        self.assertEqual(generated_skill.read_text(), claude_skill.read_text())
        self.assertTrue(
            (self.home / ".agents/skills/pr-review-draft/agents/openai.yaml").is_file()
        )
        opencode_command = (
            self.home / ".config/opencode/commands/pr-review-draft.md"
        )
        self.assertIn(
            "Generated by install-agent-commands.", opencode_command.read_text()
        )
        self.assertIn("Draft a review of PR $ARGUMENTS", opencode_command.read_text())
        self.assertFalse(legacy_command.exists())
        self.assertEqual("Unmanaged command\n", unmanaged_command.read_text())
        self.assertEqual(
            "Unmanaged OpenCode command\n", unmanaged_opencode_command.read_text()
        )
        self.assertEqual(before, self.repository_status())

