    def test_profiles_preserve_unmanaged_local_config_and_state(self) -> None:
        profiles = (
            (
                "ai/.bin/pi-profile",
                "codex",
                self.home / ".omp/agent/config.yml",
                self.home / ".omp/agent/.active",
            ),
            (
                "ai/.bin/opencode-profile",
                "gpt",
                self.home / ".config/opencode/opencode.jsonc",
                self.home / ".config/opencode/.active",
            ),
        )

        for script, profile, config, active in profiles:
            config.parent.mkdir(parents=True, exist_ok=True)
            config.write_text("user configuration\n")
            completed = self.run_command(script, "use", profile, expected_code=1)
            self.assertIn("refusing to overwrite unmanaged config", completed.stderr)
            self.assertEqual("user configuration\n", config.read_text())
            config.unlink()

            external_state = self.home / f"{profile}-external-state"
            external_state.write_text("user state\n")
            active.symlink_to(external_state)
            completed = self.run_command(script, "use", profile, expected_code=1)
            self.assertIn("refusing to overwrite unmanaged active profile", completed.stderr)
            self.assertEqual("user state\n", external_state.read_text())
            active.unlink()
            active.write_text("unmanaged state\n")
            completed = self.run_command(script, "use", profile, expected_code=1)
            self.assertIn("refusing to overwrite unmanaged active profile", completed.stderr)
            self.assertEqual("unmanaged state\n", active.read_text())
            active.write_text("common\n")
            completed = self.run_command(script, "use", profile, expected_code=1)
            self.assertIn("refusing to overwrite unmanaged active profile", completed.stderr)
            self.assertEqual("common\n", active.read_text())
            self.assertFalse(config.exists())

