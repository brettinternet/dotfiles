    def test_make_ai_is_idempotent_without_dirtying_checkout(self) -> None:
        before = self.repository_status()
        repository_envrc = ROOT / "base/.envrc"
        if not (repository_envrc.exists() or repository_envrc.is_symlink()):
            local_envrc = self.home / ".envrc"
            local_envrc.write_text("\n")
            repository_envrc.symlink_to(local_envrc)
            self.addCleanup(repository_envrc.unlink)

        legacy_links = {
            self.home / ".agents/skills/pr-review-draft": ROOT
            / "ai/.agents/skills/pr-review-draft",
            self.home / ".claude/skills/pr-review-draft": ROOT
            / "ai/.agents/skills/pr-review-draft",
            self.home / ".omp/agent/config.yml": ROOT / "ai/pi/config.yml",
            self.home / ".config/opencode/opencode.jsonc": ROOT
            / "ai/opencode/opencode.jsonc",
        }
        for link, target in legacy_links.items():
            link.parent.mkdir(parents=True, exist_ok=True)
            link.symlink_to(target)

        self.run_command("make", "ai")
        self.run_command("make", "ai")

        self.assertEqual(before, self.repository_status())
        self.assertFalse((self.home / ".agents/skills/pr-review-draft").is_symlink())
        self.assertFalse((self.home / ".claude/skills/pr-review-draft").is_symlink())
        self.assertFalse((self.home / ".omp/agent/config.yml").is_symlink())
        self.assertFalse(
            (self.home / ".config/opencode/opencode.jsonc").is_symlink()
        )
        self.assertFalse(
            (self.home / ".claude/commands/pr-review-draft.md").exists()
        )
        opencode_agents = self.home / ".config/opencode/AGENTS.md"
        self.assertTrue(opencode_agents.is_symlink())
        self.assertEqual((ROOT / "ai/AGENTS.md").resolve(), opencode_agents.resolve())
        for definition in (
            self.home / ".claude/agents/executor.md",
            self.home / ".omp/agents/explore.md",
            self.home / ".config/opencode/agents/explore.md",
            self.home / ".codex/agents/executor.toml",
        ):
            self.assertTrue(definition.is_file(), definition)
            self.assertFalse(definition.is_symlink(), definition)

